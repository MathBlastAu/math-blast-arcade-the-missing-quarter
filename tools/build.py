#!/usr/bin/env python3
"""build.py - merge manifest fragments and embed every asset as base64 into
js/assets-embedded.js so the game runs by double-clicking index.html (file://),
where browsers block XHR and taint WebGL textures loaded from disk.

Usage: python3 tools/build.py
"""
import base64, glob, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(ROOT, "assets")


def main():
    man = {"sheets": {}, "images": {}, "fonts": {}, "voice": {}, "meta": {}}
    for f in sorted(glob.glob(os.path.join(A, "manifest", "*.json"))):
        part = os.path.splitext(os.path.basename(f))[0]
        d = json.load(open(f))
        for k in ("sheets", "images", "fonts", "voice"):
            for name, v in d.get(k, {}).items():
                if name in man[k]:
                    print("WARNING duplicate key", k, name, "in", part)
                man[k][name] = v
        extra = {k: v for k, v in d.items() if k not in ("sheets", "images", "fonts", "voice")}
        if extra:
            man["meta"][part] = extra
    files, text, audio = {}, {}, {}
    missing = []

    def embed(rel, mime):
        p = os.path.join(A, rel)
        if not os.path.exists(p):
            missing.append(rel); return
        files[rel] = "data:%s;base64,%s" % (mime, base64.b64encode(open(p, "rb").read()).decode())

    for v in list(man["sheets"].values()) + list(man["images"].values()):
        embed(v["file"], "image/png")
    for v in man["fonts"].values():
        embed(v["png"], "image/png")
        p = os.path.join(A, v["fnt"])
        if os.path.exists(p):
            text[v["fnt"]] = open(p, encoding="utf-8").read()
        else:
            missing.append(v["fnt"])
    for vid, v in man["voice"].items():
        p = os.path.join(A, v["file"])
        if os.path.exists(p):
            audio["voice/" + vid] = "data:audio/mpeg;base64," + base64.b64encode(open(p, "rb").read()).decode()
    out = os.path.join(ROOT, "js", "assets-embedded.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("/* GENERATED by tools/build.py - do not edit. Source files are in assets/. */\n")
        f.write("window.MB_ASSETS = ")
        json.dump({"manifest": man, "files": files, "text": text, "audio": audio}, f, separators=(",", ":"))
        f.write(";\n")
    print("sheets %d, images %d, fonts %d, voice clips %d -> %s (%.0f KB)" % (
        len(man["sheets"]), len(man["images"]), len(man["fonts"]), len(audio), os.path.relpath(out, ROOT),
        os.path.getsize(out) / 1024))
    if missing:
        print("MISSING FILES:", missing); sys.exit(1)
    return man


if __name__ == "__main__":
    man = main()
    if "-v" in sys.argv:
        for k, v in sorted(man["sheets"].items()):
            an = {a: (d["frames"][0], d["frames"][-1], d["fps"], int(d["loop"])) for a, d in v.get("anims", {}).items()}
            print(k, v["fw"], v["fh"], an, v.get("names", ""))
        print("images:", sorted(man["images"].keys()))
        print("meta:", json.dumps(man["meta"]))
